/**
 * 囲み（BubbleSets）のパラメータ。cytoscape-bubblesets の `addPath` に渡す。
 *
 * BubbleSets はノードとエッジの周りに影響場（ポテンシャル）を張って、その等値線を輪郭にする。
 * ノードの配置に沿って形が変わるのはこの仕組みのおかげだが、計算はピクセルグリッド上の
 * マーチングなので安くはない。シミュレーション中も破綻しないよう、次の 2 つで抑えている。
 *
 * - `pixelGroup`: グリッドの粗さ。大きいほど速く、輪郭は粗くなる（既定 4）
 * - `throttle`: 位置が動いたときの再計算の間隔（ms）。粘性のある追従にも効く
 *
 * `nodeR0`/`nodeR1` は影響場の内径・外径で、これが実質の「囲みの余白」になる。
 * `virtualEdges` は離れたメンバーどうしを仮想の線でつないで、1 ユニットが複数の島に
 * 割れるのを防ぐ（cytoscape-bubblesets 側の既定は false なので明示的に立てる）。
 */
export const HULL_OPTIONS = {
  throttle: 80,
  pixelGroup: 5,
  virtualEdges: true,
  nodeR0: 14,
  nodeR1: 42,
  edgeR0: 10,
  edgeR1: 22,
  morphBuffer: 14
}

