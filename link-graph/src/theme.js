/**
 * 囲みの余白（px）。blob の丸みで四隅が欠けるぶんを吸収する。
 *
 * **必ず px で指定する。** fcose は余白を `parseInt(css("padding"))` で読むので、
 * `"17%"` のような割合指定は「17px」と解釈されてしまう。描画される blob だけが大きくなり、
 * レイアウトはその大きさを知らないまま詰めるので、囲みどうしが激しく重なる。
 *
 * 増やすと四隅のノードは収まりやすくなるが、囲みが膨らんで重なりやすくもなる。
 * 現状の実データ（CG系のみ表示）では 40 前後が重なりの少ない値だった。
 */
export const UNIT_PADDING = 40

